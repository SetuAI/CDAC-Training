# SECTION 2 -- THE THREE TAIL REGIMES
# ==============================================================================

def classify_kurtosis(excess):
    """
    Name the tail regime from an excess kurtosis value.

        LEPTOKURTIC   excess > 0   fat tails, extremes more common than normal
        MESOKURTIC    excess ~ 0   normal-like tails
        PLATYKURTIC   excess < 0   thin tails, extremes rarer than normal
    """
    if excess > 1.0:
        return "LEPTOKURTIC", "fat tails -- extreme values more common than a normal model expects"
    elif excess < -1.0:
        return "PLATYKURTIC", "thin tails -- extreme values rarer than a normal model expects"
    else:
        return "MESOKURTIC", "tails roughly like a normal distribution"


def build_tail_examples(seed=7):
    """
    Generate three distributions with the same mean and standard deviation
    but different tail weight.

    Holding mean and standard deviation constant is the important part. It
    proves kurtosis is measuring something the first three statistics cannot
    see.
    """
    rng = np.random.default_rng(seed)
    size = 20_000

    # MESOKURTIC: a normal distribution. Excess kurtosis near 0.
    normal = pd.Series(rng.normal(loc=0, scale=1, size=size))

    # LEPTOKURTIC: Student's t with low degrees of freedom. Same general shape
    # as a normal but with much heavier tails. This is the standard model for
    # financial returns precisely because real returns have fat tails.
    heavy = pd.Series(rng.standard_t(df=4, size=size))

    # PLATYKURTIC: a uniform distribution. Hard boundaries, so no tails at all.
    thin = pd.Series(rng.uniform(low=-1, high=1, size=size))

    # Standardise all three to mean 0 and standard deviation 1, so the only
    # remaining difference between them is shape.
    normal = (normal - normal.mean()) / normal.std()
    heavy = (heavy - heavy.mean()) / heavy.std()
    thin = (thin - thin.mean()) / thin.std()

    return {"normal (mesokurtic)": normal,
            "Student t, df=4 (leptokurtic)": heavy,
            "uniform (platykurtic)": thin}


# ==============================================================================
# SECTION 3 -- WHY KURTOSIS IS A RISK METRIC
# ==============================================================================

def count_extreme_observations(series, thresholds=(2, 3, 4, 5)):
    """
    Count how many observations sit beyond a given number of standard
    deviations, and compare that to what a normal distribution predicts.

    This converts an abstract kurtosis value into a business quantity:
    how often does the bad day actually happen, versus how often the model
    said it would?
    """
    # Standardise so thresholds are in standard deviation units.
    z = (series - series.mean()) / series.std()

    # Probabilities a normal distribution assigns to being beyond k sigma,
    # in either direction. These are the textbook values.
    normal_probability = {2: 0.0455, 3: 0.0027, 4: 0.0000633, 5: 0.00000057}

    results = []
    for k in thresholds:
        # .abs() makes both tails count. .sum() on a True/False Series counts
        # the True values, because True behaves as 1 in arithmetic.
        observed_count = (z.abs() > k).sum()
        observed_rate = observed_count / len(series)
        expected_rate = normal_probability[k]

        results.append({
            "threshold": f"beyond {k} sigma",
            "observed": observed_count,
            "observed_rate": observed_rate,
            "expected_rate": expected_rate,
            # How many times more often than the normal model predicted.
            "ratio": observed_rate / expected_rate if expected_rate > 0 else float("nan"),
        })

    return results


def show_risk_case(seed=7):
    """
    Meridian's treasury portfolio: 10 years of daily returns.

    The risk model assumes normality. We generate returns with genuinely
    fat tails and then ask the normal model how often a 4-sigma day should
    happen, versus how often it did.
    """
    rng = np.random.default_rng(seed)

    # Roughly 10 years of trading days.
    days = 2520

    # Fat-tailed daily returns, scaled to about 1% daily volatility.
    returns = pd.Series(rng.standard_t(df=3, size=days) * 0.01)

    print(f"\n  {days} daily returns")
    print(f"    mean            : {returns.mean() * 100:8.4f}%")
    print(f"    std deviation   : {returns.std() * 100:8.4f}%")
    print(f"    skewness        : {returns.skew():8.2f}")
    print(f"    excess kurtosis : {returns.kurt():8.2f}")

    regime, meaning = classify_kurtosis(returns.kurt())
    print(f"    -> {regime}: {meaning}")

    print(f"\n  {'threshold':<18} {'observed':>10} {'observed %':>12} "
          f"{'normal model %':>16} {'times worse':>13}")
    print("  " + "-" * 74)

    for row in count_extreme_observations(returns):
        print(f"  {row['threshold']:<18} {row['observed']:>10} "
              f"{row['observed_rate'] * 100:>11.3f}% "
              f"{row['expected_rate'] * 100:>15.4f}% "
              f"{row['ratio']:>12.1f}x")

    print("\n  A normal model would call the 4-sigma days a once-in-60-years")
    print("  event. Here they turn up repeatedly in a decade. That gap between")
    print("  assumed and actual tail weight is what kurtosis is measuring, and")
    print("  it is a large part of what went wrong with risk models in 2008.")


# ==============================================================================
# SECTION 4 -- THE PEAKEDNESS MISREADING
# ==============================================================================

def show_peakedness_myth():
    """
    Demonstrate that kurtosis is about tails, not about the height of the peak.

    The common textbook error is "high kurtosis means a tall sharp peak".
    It does not. The fourth power gives observations near the centre almost
    no weight at all, so the centre barely participates in the calculation.

    We prove it by taking a normal distribution and moving observations
    outward into the tails while leaving the centre alone.
    """
    rng = np.random.default_rng(99)

    base = pd.Series(rng.normal(0, 1, 10_000))
    base = (base - base.mean()) / base.std()

    # Copy the data and push a small number of observations far out into the
    # tails. The bulk of the distribution -- the middle -- is untouched.
    fattened = base.copy()
    # Pick 40 positions at random and multiply those values by 5.
    positions = rng.choice(len(fattened), size=40, replace=False)
    fattened.iloc[positions] = fattened.iloc[positions] * 5

    # Re-standardise so both series still have mean 0 and standard deviation 1.
    fattened = (fattened - fattened.mean()) / fattened.std()

    # Count observations near the centre in each version.
    centre_base = ((base.abs() < 0.5).sum() / len(base)) * 100
    centre_fat = ((fattened.abs() < 0.5).sum() / len(fattened)) * 100

    print(f"\n  {'':<26} {'original':>12} {'tails fattened':>16}")
    print("  " + "-" * 56)
    print(f"  {'excess kurtosis':<26} {base.kurt():>12.2f} {fattened.kurt():>16.2f}")
    print(f"  {'% within 0.5 sigma':<26} {centre_base:>11.1f}% {centre_fat:>15.1f}%")
    print(f"  {'% beyond 3 sigma':<26} "
          f"{(base.abs() > 3).sum() / len(base) * 100:>11.2f}% "
          f"{(fattened.abs() > 3).sum() / len(fattened) * 100:>15.2f}%")

    print("\n  We changed 40 observations out of 10,000, all of them far from")
    print("  the centre. Kurtosis moved sharply. The proportion of data near")
    print("  the middle barely changed.")
    print("\n  Read kurtosis as: how much of the variance is being generated by")
    print("  extreme observations. Not as: how tall is the peak.")


