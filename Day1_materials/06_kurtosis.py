def full_diagnostic(series, label):
    """
    Run every statistic from this course in the order you should run them,
    and print the decision each one leads to.

    This is the function to reuse on real data.
    """
    n = len(series)
    mean = series.mean()
    median = series.median()
    sd = series.std()
    q1, q3 = series.quantile(0.25), series.quantile(0.75)
    iqr = q3 - q1
    skew = series.skew()
    kurt = series.kurt()

    print(f"\n{'=' * 74}")
    print(f"DIAGNOSTIC: {label}")
    print(f"{'=' * 74}")

    print(f"\n  STEP 1 -- size and centre")
    print(f"    n      = {n}")
    print(f"    mean   = {mean:.2f}")
    print(f"    median = {median:.2f}")

    gap_pct = (mean - median) / median * 100 if median != 0 else 0
    print(f"    the mean sits {gap_pct:+.1f}% from the median")

    print(f"\n  STEP 2 -- spread")
    print(f"    std deviation = {sd:.2f}")
    print(f"    IQR           = {iqr:.2f}")
    print(f"    CV            = {sd / mean:.2f}" if mean != 0 else "    CV: not meaningful")

    print(f"\n  STEP 3 -- symmetry")
    print(f"    skewness = {skew:+.2f}")
    if abs(skew) > 1:
        print(f"    -> highly skewed. Report the MEDIAN as the headline number.")
    elif abs(skew) > 0.5:
        print(f"    -> moderately skewed. Report the median alongside the mean.")
    else:
        print(f"    -> roughly symmetric. The mean is safe.")

    print(f"\n  STEP 4 -- tails")
    print(f"    excess kurtosis = {kurt:+.2f}")
    regime, meaning = classify_kurtosis(kurt)
    print(f"    -> {regime}: {meaning}")

    print(f"\n  STEP 5 -- flag extremes with the IQR fence")
    lower, upper = q1 - 1.5 * iqr, q3 + 1.5 * iqr
    flagged = series[(series < lower) | (series > upper)]
    print(f"    fence: [{lower:.2f}, {upper:.2f}]")
    if len(flagged):
        print(f"    flagged: {sorted(flagged.tolist())[:10]}"
              f"{' ...' if len(flagged) > 10 else ''}  ({len(flagged)} total)")
        print(f"    -> go and look at these before deciding anything.")
    else:
        print(f"    nothing flagged")


