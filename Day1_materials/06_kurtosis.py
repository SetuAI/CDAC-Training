# SECTION 1 -- KURTOSIS FROM SCRATCH
# ==============================================================================

def excess_kurtosis_population(values):
    """
    The straightforward population version of excess kurtosis.

            raw    = mean of ((x - mean) / sigma) ^ 4
            excess = raw - 3

    where sigma is the POPULATION standard deviation (divide by n).

    Why the FOURTH power:
        - It removes the sign completely. A deviation of -3 and a deviation of
          +3 both contribute 81. Kurtosis is direction-blind by design -- it
          reads both tails together. Skewness is the statistic for direction.
        - It amplifies distance even harder than the cube in skewness. A value
          4 standard deviations out contributes 256 units; a value half a
          standard deviation out contributes 0.0625.
        - So the statistic is driven almost entirely by the far observations.
          Values near the centre are effectively invisible to it.

    Why subtract 3: the normal distribution has a raw kurtosis of exactly 3,
    so subtracting it makes "normal" the zero point and turns the statistic
    into a comparison rather than an absolute quantity.
    """
    n = len(values)

    if n < 4:
        raise ValueError("kurtosis needs at least 4 observations to be meaningful")

    mean = sum(values) / n

    # Population standard deviation -- divide by n, not n-1.
    variance = sum((v - mean) ** 2 for v in values) / n
    sd = math.sqrt(variance)

    if sd == 0:
        return 0.0

    # Average of the standardised deviations raised to the fourth power.
    raw = sum(((v - mean) / sd) ** 4 for v in values) / n

    return raw - 3.0


def excess_kurtosis_sample(values):
    """
    The sample-adjusted version, which is what pandas .kurt() returns.

    The correction factors below do the same job as n-1 in the variance:
    they remove a bias that appears when estimating a population quantity
    from a small sample. On large samples the two versions converge.

    You will rarely type this formula out. It is here so the number pandas
    gives you is not a black box.
    """
    n = len(values)

    if n < 4:
        raise ValueError("sample kurtosis needs at least 4 observations")

    mean = sum(values) / n
    # Note: sample standard deviation here, dividing by n-1.
    sd = math.sqrt(sum((v - mean) ** 2 for v in values) / (n - 1))

    if sd == 0:
        return 0.0

    fourth_power_sum = sum(((v - mean) / sd) ** 4 for v in values)

    # Two correction terms, applied to the sum and then subtracted.
    first_term = (n * (n + 1)) / ((n - 1) * (n - 2) * (n - 3)) * fourth_power_sum
    second_term = (3 * (n - 1) ** 2) / ((n - 2) * (n - 3))

    return first_term - second_term


def show_kurtosis_contributions(values, label):
    """
    Show how much each observation contributes to the kurtosis total.

    This is the most direct way to see what kurtosis actually measures. The
    share column collapses almost entirely onto the extreme observations,
    which is the whole point of the fourth power.
    """
    n = len(values)
    mean = sum(values) / n
    sd = math.sqrt(sum((v - mean) ** 2 for v in values) / n)

    print(f"\n{label}")
    print(f"  mean = {mean:.2f}, sigma = {sd:.2f}\n")
    print(f"  {'value':>8} {'z':>10} {'z^4':>14} {'share of total':>16}")
    print("  " + "-" * 52)

    fourth_powers = [((v - mean) / sd) ** 4 for v in values]
    total = sum(fourth_powers)

    for v, p in zip(values, fourth_powers):
        z = (v - mean) / sd
        print(f"  {v:>8.0f} {z:>+10.3f} {p:>14.3f} {p / total * 100:>15.1f}%")

    print("  " + "-" * 52)
    print(f"  {'SUM':>8} {'':>10} {total:>14.3f}")
    print(f"\n  raw kurtosis    = {total / n:.3f}")
    print(f"  excess kurtosis = {total / n - 3:.3f}")


